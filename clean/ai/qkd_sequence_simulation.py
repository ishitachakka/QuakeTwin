"""
qkd_sequence_simulation.py
--------------------------
SeQUeNCe-inspired network simulation with QKD (BB84 protocol) for
Cloud5 Digital Twin communication layer.

This module simulates:
1. Quantum network channel conditions (latency, packet loss, fidelity)
2. BB84 QKD protocol for secure key distribution
3. Impact of communication degradation on Digital Twin state updates
4. Comparison of secured (QKD) vs unsecured channels under attack

Research contribution: Demonstrates how communication constraints
affect QRL decision-making quality in the Digital Twin pipeline.

Usage:
    from qkd_sequence_simulation import NetworkSimulator, QKDChannel, run_experiments
    results = run_experiments()
"""

import numpy as np
import random
import time
import json
import math
from dataclasses import dataclass, field, asdict
from typing import List, Tuple, Dict, Optional
from enum import Enum


# ---------------------------------------------------------------------------
# Data Structures
# ---------------------------------------------------------------------------

class ChannelStatus(Enum):
    SECURE = "secure"
    DEGRADED = "degraded"
    ATTACKED = "attacked"
    FAILED = "failed"


@dataclass
class NetworkCondition:
    latency_ms: float          # one-way delay in milliseconds
    packet_loss_rate: float    # 0.0 – 1.0
    jitter_ms: float           # latency variance
    bandwidth_mbps: float      # available bandwidth
    channel_status: ChannelStatus = ChannelStatus.SECURE

    def effective_latency(self) -> float:
        """Latency with jitter applied."""
        return self.latency_ms + np.random.normal(0, self.jitter_ms)

    def is_packet_received(self) -> bool:
        return random.random() > self.packet_loss_rate


@dataclass
class QKDKeyBlock:
    """A shared secret key block generated by BB84."""
    key_bits: List[int]
    key_length: int
    qber: float          # Quantum Bit Error Rate (should be < 0.11 for BB84)
    is_secure: bool
    generation_time_ms: float

    @property
    def secure_key_rate(self) -> float:
        """Bits per second after privacy amplification."""
        if not self.is_secure:
            return 0.0
        # Simplified Shor-Preskill bound
        h = lambda p: -p * math.log2(p + 1e-10) - (1-p) * math.log2(1-p + 1e-10)
        secure_fraction = max(0, 1 - 2 * h(self.qber))
        return (self.key_length * secure_fraction) / (self.generation_time_ms / 1000)


@dataclass
class SensorReading:
    """Simulated Digital Twin sensor payload."""
    sensor_id: str
    timestamp: float
    pci_value: float           # Pavement Condition Index 0–100
    traffic_level: str         # NORMAL / WATCH / CONGESTED / CRITICAL
    latitude: float
    longitude: float
    raw_features: List[float]  # CV feature vector


@dataclass
class TransmittedReading:
    """A SensorReading after passing through the network."""
    original: SensorReading
    received: bool
    corrupted: bool
    latency_ms: float
    encrypted: bool
    tampered: bool = False

    def fidelity(self) -> float:
        if not self.received:
            return 0.0
        if self.tampered:
            return 0.3
        if self.corrupted:
            return max(0, 1.0 - (self.latency_ms / 2000))
        return 1.0


# ---------------------------------------------------------------------------
# BB84 QKD Protocol (simplified)
# ---------------------------------------------------------------------------

class BB84Protocol:
    """
    Simplified BB84 Quantum Key Distribution simulation.

    BB84 uses two conjugate bases (+, x). Alice sends qubits; Bob measures.
    They compare bases over a public channel and keep matching bits.
    QBER detects eavesdropping (Eve introduces errors).
    """

    SECURITY_THRESHOLD_QBER = 0.11  # Shor-Preskill bound

    def __init__(self, raw_key_length: int = 256, eavesdrop_probability: float = 0.0):
        self.raw_key_length = raw_key_length
        self.eavesdrop_probability = eavesdrop_probability

    def generate_key(self) -> QKDKeyBlock:
        start = time.time()

        # Alice generates random bits and bases
        alice_bits = np.random.randint(0, 2, self.raw_key_length)
        alice_bases = np.random.randint(0, 2, self.raw_key_length)  # 0=+, 1=x

        # Bob chooses random measurement bases
        bob_bases = np.random.randint(0, 2, self.raw_key_length)

        # Eve intercepts with some probability (intercept-resend attack)
        eve_bases = np.random.randint(0, 2, self.raw_key_length)
        eve_active = np.random.random(self.raw_key_length) < self.eavesdrop_probability

        # Simulate transmission
        received_bits = alice_bits.copy()
        for i in range(self.raw_key_length):
            if eve_active[i]:
                # Eve measures and resends — introduces 25% error on mismatched bases
                if eve_bases[i] != alice_bases[i]:
                    received_bits[i] = np.random.randint(0, 2)

        # Sifting: keep bits where Alice and Bob chose same basis
        matching_bases = alice_bases == bob_bases
        sifted_alice = alice_bits[matching_bases]
        sifted_bob = received_bits[matching_bases]

        # Estimate QBER on a test subset (25% of sifted key)
        test_size = max(1, len(sifted_alice) // 4)
        test_indices = np.random.choice(len(sifted_alice), test_size, replace=False)
        qber = np.mean(sifted_alice[test_indices] != sifted_bob[test_indices])

        # Final key after removing test bits
        remaining = np.delete(np.arange(len(sifted_alice)), test_indices)
        final_key = sifted_alice[remaining].tolist()

        is_secure = qber < self.SECURITY_THRESHOLD_QBER
        elapsed_ms = (time.time() - start) * 1000

        return QKDKeyBlock(
            key_bits=final_key,
            key_length=len(final_key),
            qber=float(qber),
            is_secure=is_secure,
            generation_time_ms=elapsed_ms,
        )


# ---------------------------------------------------------------------------
# SeQUeNCe-Inspired Network Channel
# ---------------------------------------------------------------------------

class QKDChannel:
    """
    Models a quantum-secured communication channel between
    sensor nodes and the Digital Twin backend.

    Combines:
    - Classical network simulation (latency, loss, jitter)
    - QKD key generation for encryption
    - Attack simulation (MITM, replay, injection)
    """

    def __init__(self, condition: NetworkCondition, use_qkd: bool = True,
                 eavesdrop_prob: float = 0.0):
        self.condition = condition
        self.use_qkd = use_qkd
        self.qkd = BB84Protocol(eavesdrop_probability=eavesdrop_prob) if use_qkd else None
        self._current_key: Optional[QKDKeyBlock] = None
        self._key_uses: int = 0
        self._key_refresh_interval: int = 50  # refresh key every N transmissions
        self.stats = {
            "total_sent": 0,
            "total_received": 0,
            "total_tampered": 0,
            "total_dropped": 0,
            "key_refreshes": 0,
        }

    def _refresh_key(self):
        if self.use_qkd:
            self._current_key = self.qkd.generate_key()
            self._key_uses = 0
            self.stats["key_refreshes"] += 1

    def transmit(self, reading: SensorReading,
                 inject_attack: bool = False) -> TransmittedReading:
        """Transmit a sensor reading through this channel."""
        self.stats["total_sent"] += 1

        # Refresh QKD key if needed
        if self.use_qkd and (self._current_key is None or
                              self._key_uses >= self._key_refresh_interval):
            self._refresh_key()

        latency = self.condition.effective_latency()
        received = self.condition.is_packet_received()
        self._key_uses += 1

        if not received:
            self.stats["total_dropped"] += 1
            return TransmittedReading(
                original=reading, received=False, corrupted=False,
                latency_ms=latency, encrypted=self.use_qkd
            )

        # Simulate bit corruption due to latency/noise
        corrupted = latency > 500 and random.random() < 0.15

        # MITM attack: only succeeds without QKD, or if QKD QBER is too high
        tampered = False
        if inject_attack and not self.use_qkd:
            tampered = True
            self.stats["total_tampered"] += 1
        elif inject_attack and self.use_qkd:
            # QKD detects eavesdropping via QBER — attack fails if key is secure
            if self._current_key and not self._current_key.is_secure:
                tampered = True
                self.stats["total_tampered"] += 1

        self.stats["total_received"] += 1
        return TransmittedReading(
            original=reading, received=True, corrupted=corrupted,
            latency_ms=latency, encrypted=self.use_qkd, tampered=tampered
        )

    @property
    def current_qber(self) -> float:
        if self._current_key:
            return self._current_key.qber
        return 0.0

    @property
    def delivery_rate(self) -> float:
        if self.stats["total_sent"] == 0:
            return 0.0
        return self.stats["total_received"] / self.stats["total_sent"]


