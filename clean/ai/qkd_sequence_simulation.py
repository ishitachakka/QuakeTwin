# Sensor Data Generator
# ---------------------------------------------------------------------------

def generate_sensor_readings(n: int = 100) -> List[SensorReading]:
    """Generate synthetic sensor readings for FGCU campus roads."""
    readings = []
    # FGCU campus bounding box
    lat_range = (26.44, 26.47)
    lon_range = (-81.80, -81.76)

    for i in range(n):
        pci = np.random.beta(5, 2) * 100  # skewed toward good condition
        readings.append(SensorReading(
            sensor_id=f"FGCU-SENSOR-{i:04d}",
            timestamp=time.time() + i,
            pci_value=float(pci),
            traffic_level=random.choice(["NORMAL", "WATCH", "CONGESTED", "CRITICAL"]),
            latitude=random.uniform(*lat_range),
            longitude=random.uniform(*lon_range),
            raw_features=[random.uniform(0, 1) for _ in range(8)],
        ))
    return readings


