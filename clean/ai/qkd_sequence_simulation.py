# QRL Decision Quality Model
# ---------------------------------------------------------------------------

class QRLDecisionModel:
    """
    Simplified QRL decision model that scores decision quality
    based on the fidelity of incoming sensor data.

    In the real system this is the PennyLane QRL agent.
    Here we model how data quality degrades decision accuracy.
    """

    RISK_LEVELS = ["NORMAL", "WATCH", "CONGESTED", "CRITICAL"]

    def __init__(self):
        self._decision_history: List[Dict] = []

    def classify(self, transmitted: TransmittedReading) -> Dict:
        """Return a risk classification given (possibly degraded) sensor data."""
        if not transmitted.received:
            # Fallback to last known state
            return {
                "risk_level": "WATCH",
                "confidence": 0.25,
                "data_quality": 0.0,
                "decision_valid": False,
            }

        fidelity = transmitted.fidelity()
        noise = np.random.normal(0, 0.05 * (1 - fidelity))

        # Simulate PCI-based classification with noise
        pci = max(0, min(100, transmitted.original.pci_value + noise * 100))

        if pci >= 80:
            true_level = "NORMAL"
        elif pci >= 65:
            true_level = "WATCH"
        elif pci >= 45:
            true_level = "CONGESTED"
        else:
            true_level = "CRITICAL"

        # Confidence degrades with fidelity
        base_confidence = 0.85 + 0.12 * fidelity
        confidence = max(0.1, min(1.0, base_confidence + np.random.normal(0, 0.03)))

        # With low fidelity, classification may be wrong
        if fidelity < 0.5 and random.random() < (1 - fidelity):
            idx = self.RISK_LEVELS.index(true_level)
            idx = max(0, min(3, idx + random.choice([-1, 1])))
            returned_level = self.RISK_LEVELS[idx]
        else:
            returned_level = true_level

        result = {
            "risk_level": returned_level,
            "true_risk_level": true_level,
            "confidence": round(confidence, 3),
            "data_quality": round(fidelity, 3),
            "decision_valid": returned_level == true_level,
            "latency_ms": round(transmitted.latency_ms, 2),
            "encrypted": transmitted.encrypted,
            "tampered": transmitted.tampered,
        }
        self._decision_history.append(result)
        return result

    def accuracy(self) -> float:
        if not self._decision_history:
            return 0.0
        return sum(1 for d in self._decision_history if d["decision_valid"]) / len(self._decision_history)

    def mean_confidence(self) -> float:
        if not self._decision_history:
            return 0.0
        return np.mean([d["confidence"] for d in self._decision_history])


